export function getZoneUnlockToolId(zone: MakeupZoneId): UnlockableToolId | null {
  switch (zone) {
    case 'concealer':
      return 'zone_concealer';
    case 'contour':
      return 'zone_contour';
    case 'highlighter':
      return 'zone_highlighter';
    case 'eyeshadow_crease':
      return 'zone_eyeshadow_crease';
    case 'eyeliner':
      return 'zone_eyeliner';
    case 'mascara':
      return 'zone_mascara';
    case 'lipliner':
      return 'zone_lipliner';
    case 'lipgloss':
      return 'zone_lipgloss';
    default:
      return null;
  }
}

export function getToolInfo(id: UnlockableToolId): UnlockableToolInfo {
  return UNLOCKABLE_TOOLS.find((t) => t.id === id)!;
}

